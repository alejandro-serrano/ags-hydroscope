"""Spatial split of the Aguascalientes labels into "finetune" and "test" by 8x8-cell blocks.

Usage::

    python scripts/split_ags.py [--labels data/ags/labels.csv] [--force]

A whole block goes to one split. The block list is shuffled n_trials times (seed 0) and cut in
half; we keep the partition whose class fractions in test are closest to 0.5 (smallest maximum
deviation across classes). Rows with label "skip" take the split of their block.

Outputs:
    data/ags/labels.csv            the empty ``split`` column is filled
    configs/ags_block_split.csv    block_id,split
    docs/data_card.md              the table between the BEGIN/END markers is replaced
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from hydroscope.data.eurosat import CLASSES
from hydroscope.data.labels import SKIP, load_labels

ROOT = Path(__file__).resolve().parents[1]
MIN_TEST = 10
BEGIN = "<!-- BEGIN generated by scripts/split_ags.py -->"
END = "<!-- END generated by scripts/split_ags.py -->"


def block_class_counts(labels: pd.DataFrame) -> pd.DataFrame:
    """Patches per class in each block (rows = block_id, columns = CLASSES); skip rows excluded."""
    labeled = labels[labels["label"] != SKIP]
    counts = pd.crosstab(labeled["block_id"], labeled["label"])
    counts = counts.reindex(columns=CLASSES, fill_value=0)
    # blocks that only have skip rows still need a split
    return counts.reindex(sorted(labels["block_id"].unique()), fill_value=0)


def max_deviation(counts: np.ndarray, test_mask: np.ndarray) -> float:
    """Largest |fraction of a class in test - 0.5| over the classes that have patches."""
    total = counts.sum(axis=0)
    in_test = counts[test_mask].sum(axis=0)
    has_patches = total > 0
    return float(np.abs(in_test[has_patches] / total[has_patches] - 0.5).max())


def choose_split(
    labels: pd.DataFrame, n_trials: int = 20000, seed: int = 0
) -> tuple[dict[str, str], float]:
    """Pick the best random half/half partition of the blocks.

    Returns the map block_id -> "finetune" / "test" and its maximum deviation.
    """
    counts_df = block_class_counts(labels)
    block_ids = list(counts_df.index)
    counts = counts_df.to_numpy()
    n_blocks = len(block_ids)
    n_finetune = n_blocks // 2
    rng = np.random.default_rng(seed)
    best_order = None
    best_dev = None
    for _ in range(n_trials):
        order = rng.permutation(n_blocks)
        test_mask = np.zeros(n_blocks, dtype=bool)
        test_mask[order[n_finetune:]] = True
        dev = max_deviation(counts, test_mask)
        if best_dev is None or dev < best_dev:
            best_dev = dev
            best_order = order
    if best_order is None:
        raise ValueError("n_trials must be at least 1")
    block_split = {}
    for block_id in block_ids:
        block_split[block_id] = "finetune"
    for i in best_order[n_finetune:]:
        block_split[block_ids[i]] = "test"
    return block_split, best_dev


def apply_split(labels: pd.DataFrame, block_split: dict[str, str]) -> pd.DataFrame:
    """Copy of labels with the ``split`` column set from the block of every row."""
    out = labels.copy()
    out["split"] = out["block_id"].map(block_split)
    return out


def class_table(labels: pd.DataFrame) -> pd.DataFrame:
    """Per-class totals by split (labels must have the split filled); skip rows excluded."""
    labeled = labels[labels["label"] != SKIP]
    rows = []
    for name in CLASSES:
        part = labeled[labeled["label"] == name]
        n_finetune = int((part["split"] == "finetune").sum())
        n_test = int((part["split"] == "test").sum())
        total = n_finetune + n_test
        pct = 100 * n_test / total if total > 0 else float("nan")
        rows.append(
            {
                "class": name,
                "total": total,
                "finetune": n_finetune,
                "test": n_test,
                "% test": pct,
                "flag": "< 10 in test" if n_test < MIN_TEST else "",
            }
        )
    return pd.DataFrame(rows)


def table_to_text(table: pd.DataFrame) -> str:
    """Plain-text table for the console."""
    shown = table.copy()
    if "% test" in shown.columns:
        shown["% test"] = shown["% test"].round(1)
    return shown.to_string(index=False)


def table_to_markdown(table: pd.DataFrame) -> str:
    """Markdown table (same columns as the console table)."""
    lines = [
        "| Class | Total | Finetune | Test | % test | Flag |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for _, r in table.iterrows():
        lines.append(
            f"| {r['class']} | {r['total']} | {r['finetune']} | {r['test']} "
            f"| {r['% test']:.1f} | {r['flag']} |"
        )
    return "\n".join(lines)


def split_summary(labels: pd.DataFrame) -> pd.DataFrame:
    """Blocks, labeled cells and skipped cells in each split."""
    rows = []
    for name in ["finetune", "test"]:
        part = labels[labels["split"] == name]
        rows.append(
            {
                "split": name,
                "blocks": part["block_id"].nunique(),
                "cells": len(part),
                "labeled": int((part["label"] != SKIP).sum()),
                "skip": int((part["label"] == SKIP).sum()),
            }
        )
    return pd.DataFrame(rows)


def summary_to_markdown(summary: pd.DataFrame) -> str:
    """Markdown table of split_summary."""
    lines = ["| Split | Blocks | Cells | Labeled | Skip |", "| --- | ---: | ---: | ---: | ---: |"]
    for _, r in summary.iterrows():
        lines.append(
            f"| {r['split']} | {r['blocks']} | {r['cells']} | {r['labeled']} | {r['skip']} |"
        )
    return "\n".join(lines)


def build_generated_block(
    table: pd.DataFrame, summary: pd.DataFrame, max_dev: float, n_trials: int, seed: int
) -> str:
    """Markdown between the BEGIN/END markers of the data card."""
    lines = [
        BEGIN,
        "",
        f"Split chosen from {n_trials} random half/half partitions of the blocks (seed {seed}); "
        f"maximum deviation of a class from 50 % in test: {max_dev:.4f}.",
        "",
        summary_to_markdown(summary),
        "",
        table_to_markdown(table),
        "",
        END,
    ]
    return "\n".join(lines)


def replace_generated_block(text: str, block: str) -> str:
    """Replace the BEGIN/END section of ``text`` with ``block``."""
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("BEGIN/END markers not found in the data card")
    return text[:start] + block + text[end + len(END) :]


def write_block_map(block_split: dict[str, str], path: Path) -> None:
    """Write block_id,split sorted by block_id."""
    rows = []
    for block_id in sorted(block_split):
        rows.append({"block_id": block_id, "split": block_split[block_id]})
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(path, index=False)


def main() -> int:
    """Command-line entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--labels", type=Path, default=ROOT / "data/ags/labels.csv")
    parser.add_argument("--out", type=Path, default=ROOT / "configs/ags_block_split.csv")
    parser.add_argument("--data-card", type=Path, default=ROOT / "docs/data_card.md")
    parser.add_argument("--n-trials", type=int, default=20000)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--force", action="store_true", help="overwrite an existing split")
    args = parser.parse_args()

    labels = load_labels(args.labels)
    if (labels["split"] != "").any() and not args.force:
        print(
            f"ERROR: {args.labels} already has a split; use --force to overwrite", file=sys.stderr
        )
        return 1

    block_split, max_dev = choose_split(labels, args.n_trials, args.seed)
    labels = apply_split(labels, block_split)
    table = class_table(labels)
    summary = split_summary(labels)

    labels.to_csv(args.labels, index=False)
    write_block_map(block_split, args.out)
    if args.data_card.exists():
        block = build_generated_block(table, summary, max_dev, args.n_trials, args.seed)
        text = args.data_card.read_text()
        args.data_card.write_text(replace_generated_block(text, block))

    print(table_to_text(table))
    print()
    print(table_to_text(summary))
    print()
    print(f"max deviation from 50 % in test: {max_dev:.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def _num(value: float, digits: int = 1) -> str:
    return "n/a" if value is None or not np.isfinite(value) else f"{value:.{digits}f}"


def _offset(offset: Sequence[int] | None) -> str:
    return "n/a" if offset is None else f"col {offset[0]}, row {offset[1]}"


def render_report(
    info: Mapping[str, Any],
    rows: Sequence[Mapping[str, Any]],
    obs: Mapping[str, Any],
    warnings: Sequence[str],
    preview_rel: str | None,
) -> str:
    """Render docs/data_ags_check.md.

    Args:
        info: raster properties (``source``, ``n_tiles``, ``width``, ``height``, ``crs``,
            ``pixel_size``, ``dtype``, ``bands``, ``origin_aligned``).
        rows: output of :func:`compare_band`, one per spectral band.
        obs: output of :func:`summarize_valid_obs` plus ``n_valid`` and ``n_total``.
        warnings: human-readable warnings to list.
        preview_rel: relative path of the RGB preview, or ``None``.
    """
    lines = [
        HEADER,
        "",
        "# Aguascalientes raster check (April 2024)",
        "",
        "Sentinel-2 L1C median composite exported by `hydroscope.geo.gee_export`.",
        "",
        "## Raster",
        "",
        f"- Source: `{info['source']}` ({info['n_tiles']} file(s))",
        f"- Size: {info['width']} x {info['height']} px, {info['bands']} bands, `{info['dtype']}`",
        f"- CRS: {info['crs']}, pixel size: {info['pixel_size']} m",
        f"- Pixel lattice compatible with the {GRID_M} m grid (origin a multiple of "
        f"{info['pixel_size']} m): {'yes' if info['origin_aligned'] else 'NO'}",
        f"- First full {GRID_M} m cell at pixel offset: {_offset(info.get('grid_offset_px'))}",
        "",
        "## Band statistics versus EuroSAT train",
        "",
        "Statistics over pixels with `valid_obs > 0`, in digital numbers (reflectance x 10000).",
        "EuroSAT percentiles are not available (only mean and std are stored), so each",
        "Aguascalientes median is compared by its z-score `(median - EuroSAT mean) / EuroSAT std`;",
        f"bands with |z| > {Z_THRESHOLD:g} are flagged. The last column is the fraction of pixels",
        f"within EuroSAT mean +/- {WITHIN_STD:g} std. This is a screening heuristic: EuroSAT",
        "covers other regions and land covers, so a flag asks for a visual check, not a failure.",
        "",
        "| Band | Ags p2 | Ags median | Ags p98 | EuroSAT mean | EuroSAT std | z | Flag | "
        f"Within {WITHIN_STD:g} std |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | :---: | ---: |",
    ]
    for r in rows:
        within = r["within_3std"]
        within_txt = "n/a" if not np.isfinite(within) else f"{100 * within:.1f} %"
        lines.append(
            f"| {r['band']} | {_num(r['p2'])} | {_num(r['median'])} | {_num(r['p98'])} | "
            f"{_num(r['eurosat_mean'])} | {_num(r['eurosat_std'])} | {_num(r['z'], 2)} | "
            f"{'FLAG' if r['flag'] else 'ok'} | {within_txt} |"
        )
    flagged = [r["band"] for r in rows if r["flag"]]
    lines += [
        "",
        f"Flagged bands (|z| > {Z_THRESHOLD:g}): {', '.join(flagged) if flagged else 'none'}.",
        "",
        f"## `{VALID_OBS_BAND}`",
        "",
        "Count of cloud-free observations per pixel (QA60 bits 10 and 11 masked).",
        "",
        f"- Pixels with `{VALID_OBS_BAND}` > 0: {obs['n_valid']} of {obs['n_total']}",
    ]
    if obs["distinguishable"]:
        lines.append(f"- In-state pixels (rasterized boundary): {obs['n_pixels']}")
        scope = "in-state pixels"
    else:
        lines.append(
            "- No boundary given (`--boundary`): outside-state pixels and in-state pixels without "
            "observations are not distinguishable; `valid_obs == 0` is used as a proxy over all "
            "pixels of the raster."
        )
        scope = "all pixels (proxy)"
    lines += [
        f"- min / median / max over {scope}: {obs['min']} / {_num(obs['median'])} / {obs['max']}",
        f"- Pixels with `{VALID_OBS_BAND}` == 0 among {scope}: {obs['n_zero']} "
        f"({100 * obs['fraction_zero']:.2f} %)",
    ]
    valid_px = obs.get("valid_pixels")
    if valid_px is not None:
        lines += [
            f"- Over pixels with `{VALID_OBS_BAND}` > 0: min / median / max = "
            f"{valid_px['min']} / {_num(valid_px['median'])} / {valid_px['max']}; "
            f"area {_num(valid_px['area_km2'])} km2",
            "",
            f"| `{VALID_OBS_BAND}` | Pixels | Share of valid pixels |",
            "| ---: | ---: | ---: |",
        ]
        total = sum(valid_px["counts"].values())
        lines += [f"| {v} | {c} | {100 * c / total:.2f} % |" for v, c in valid_px["counts"].items()]
    lines += [
        "",
        "## Warnings",
        "",
    ]
    lines += [f"- {w}" for w in warnings] if warnings else ["None."]
    lines.append("")
    if preview_rel:
        lines += ["## Preview", "", f"![RGB preview (B04, B03, B02)]({preview_rel})", ""]
    return "\n".join(lines)


def collect_warnings(
    rows: Sequence[Mapping[str, Any]], obs: Mapping[str, Any], info: Mapping[str, Any]
) -> list[str]:
    """Warnings derived from the band comparison, valid_obs summary and raster properties."""
    out = []
    flagged = [r["band"] for r in rows if r["flag"]]
    if flagged:
        out.append(
            f"Bands with |z| > {Z_THRESHOLD:g} versus EuroSAT: {', '.join(flagged)}. "
            "Inspect the preview and the histograms before labeling."
        )
    if obs["fraction_zero"] > NO_OBS_WARN_FRACTION:
        scope = "in-state" if obs["distinguishable"] else "raster"
        out.append(
            f"{100 * obs['fraction_zero']:.2f} % of {scope} pixels have no cloud-free observation."
        )
    if not info["origin_aligned"]:
        out.append(
            f"The raster origin is not a multiple of the {PIXEL_SIZE_M} m pixel size; "
            f"{GRID_M} m grid cells will not fall on whole 64 x 64 pixel windows."
        )
    return out



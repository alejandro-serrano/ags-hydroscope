"""Check the Earth Engine export of Aguascalientes (April 2024) before it is tiled and labeled.

Usage::

    python scripts/check_ags_raster.py [--boundary data/ref/<file>]

Steps:
    1. Build ``data/ags/raw/s2_ags_2024_04.vrt`` from ``data/ags/raw/s2_ags_2024_04*.tif`` with
       ``gdalbuildvrt`` and assert 14 bands, uint16, EPSG:32613 and 10 m pixels.
    2. Per spectral band, over pixels with ``valid_obs > 0``: p2, median and p98, compared with the
       EuroSAT train mean/std (``configs/stats/eurosat_train_stats.json``).
    3. ``valid_obs`` summary, its distribution over valid pixels, and the pixel offset of the
       first full 640 m cell (the origin only has to be a multiple of the 10 m pixel size).
    4. RGB preview (B04, B03, B02, 2-98 % stretch) in ``docs/figures/ags_2024_04_rgb.png``.

Outputs:
    docs/data_ags_check.md             generated report
    docs/figures/ags_2024_04_rgb.png   downsampled preview

Bands are read one at a time (about 56 M pixels each) to keep memory low. EuroSAT percentiles are
not available (the stats file only holds mean and std), so the comparison uses the z-score of the
Aguascalientes median and the fraction of pixels within mean +/- 3 std; it is a screening heuristic,
not a pass/fail test.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from hydroscope.geo.gee_export import (
    EXPORT_CRS,
    FILE_PREFIX,
    GRID_M,
    PIXEL_SIZE_M,
    VALID_OBS_BAND,
    eurosat_band_names,
)

HEADER = "<!-- Generated by scripts/check_ags_raster.py. Do not edit by hand. -->"
ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = Path("data/ags/raw")
STATS_PATH = Path("configs/stats/eurosat_train_stats.json")
REPORT_PATH = Path("docs/data_ags_check.md")
PREVIEW_PATH = Path("docs/figures/ags_2024_04_rgb.png")

N_BANDS = 14
RGB_BANDS = ("B04", "B03", "B02")
Z_THRESHOLD = 2.0
WITHIN_STD = 3.0
PERCENTILES = (2.0, 50.0, 98.0)
NO_OBS_WARN_FRACTION = 0.01
PREVIEW_MAX_SIDE = 1600


# --------------------------------------------------------------------------------------------
# Pure statistics
# --------------------------------------------------------------------------------------------


def valid_mask(valid_obs: np.ndarray) -> np.ndarray:
    """Boolean mask of pixels with at least one cloud-free observation."""
    return np.asarray(valid_obs) > 0


def band_percentiles(
    band: np.ndarray, valid: np.ndarray, q: Sequence[float] = PERCENTILES
) -> tuple[float, float, float]:
    """Percentiles ``q`` (default p2, median, p98) of ``band`` over the ``valid`` pixels.

    Returns NaNs if there is no valid pixel.
    """
    values = np.asarray(band)[np.asarray(valid, dtype=bool)]
    if values.size == 0:
        return (float("nan"),) * len(q)  # type: ignore[return-value]
    result = np.percentile(values.astype(np.float32), list(q))
    return tuple(float(v) for v in result)  # type: ignore[return-value]


def zscore(value: float, mean: float, std: float) -> float:
    """``(value - mean) / std``; NaN if ``std`` is not positive."""
    if not std > 0:
        return float("nan")
    return float((value - mean) / std)


def flag_z(z: float, threshold: float = Z_THRESHOLD) -> bool:
    """True if ``|z| > threshold`` (NaN is not flagged)."""
    return bool(abs(z) > threshold)


def fraction_within(
    band: np.ndarray, valid: np.ndarray, mean: float, std: float, k: float = WITHIN_STD
) -> float:
    """Fraction of valid pixels with ``|value - mean| <= k * std``; NaN without valid pixels."""
    values = np.asarray(band)[np.asarray(valid, dtype=bool)]
    if values.size == 0:
        return float("nan")
    return float(np.mean(np.abs(values.astype(np.float64) - mean) <= k * std))


def summarize_valid_obs(valid_obs: np.ndarray, inside: np.ndarray | None = None) -> dict[str, Any]:
    """Summary of the ``valid_obs`` band.

    Args:
        valid_obs: count of cloud-free observations per pixel.
        inside: optional boolean mask of in-state pixels. If ``None`` the state mask is not
            available and ``valid_obs == 0`` is used as a proxy (outside-state pixels and in-state
            pixels without observations cannot be told apart).

    Returns:
        dict with ``min``, ``median``, ``max`` (over in-state pixels, or over all pixels in proxy
        mode), ``n_pixels`` (pixels counted), ``n_zero``, ``fraction_zero`` and ``distinguishable``.
    """
    vo = np.asarray(valid_obs)
    distinguishable = inside is not None
    values = vo[np.asarray(inside, dtype=bool)] if inside is not None else vo.reshape(-1)
    n = int(values.size)
    n_zero = int(np.count_nonzero(values == 0))
    return {
        "min": int(values.min()) if n else None,
        "median": float(np.median(values)) if n else None,
        "max": int(values.max()) if n else None,
        "n_pixels": n,
        "n_zero": n_zero,
        "fraction_zero": (n_zero / n) if n else float("nan"),
        "distinguishable": distinguishable,
    }


def grid_offset_px(
    left: float, top: float, grid: int = GRID_M, pixel: int = PIXEL_SIZE_M
) -> tuple[int, int] | None:
    """Pixel offset ``(col, row)`` of the first full ``grid`` cell from the raster origin.

    The ``grid`` lattice (multiples of ``grid`` metres) falls on pixel boundaries whenever the
    origin is a multiple of the pixel size, even if the raster does not start on the lattice
    (Earth Engine crops the export to the region). Returns ``None`` if the origin is not a
    multiple of ``pixel``, i.e. grid cells would not map to whole pixel windows.
    """
    if left % pixel != 0 or top % pixel != 0:
        return None
    first_x = -(-left // grid) * grid  # first lattice line at or east of the left edge
    first_y = (top // grid) * grid  # first lattice line at or south of the top edge
    return int((first_x - left) // pixel), int((top - first_y) // pixel)


def summarize_valid_pixels(valid_obs: np.ndarray, pixel: int = PIXEL_SIZE_M) -> dict[str, Any]:
    """Distribution of ``valid_obs`` over pixels with at least one cloud-free observation.

    Returns:
        dict with ``min``, ``median``, ``max``, ``area_km2`` (valid pixels x pixel area) and
        ``counts`` (``{valid_obs value: pixel count}`` for every value present), or ``None``
        statistics if no pixel is valid.
    """
    values = np.asarray(valid_obs)
    values = values[values > 0]
    if values.size == 0:
        return {"min": None, "median": None, "max": None, "area_km2": 0.0, "counts": {}}
    counts = np.bincount(values.astype(np.int64))
    return {
        "min": int(values.min()),
        "median": float(np.median(values)),
        "max": int(values.max()),
        "area_km2": float(values.size * pixel * pixel / 1e6),
        "counts": {int(v): int(c) for v, c in enumerate(counts) if c > 0},
    }


def stretch(
    band: np.ndarray, valid: np.ndarray, low: float = 2.0, high: float = 98.0
) -> np.ndarray:
    """Linear stretch of ``band`` to [0, 1] between the percentiles of its valid pixels."""
    values = np.asarray(band, dtype=np.float32)
    mask = np.asarray(valid, dtype=bool)
    if not mask.any():
        return np.zeros(values.shape, dtype=np.float32)
    lo, hi = np.percentile(values[mask], [low, high])
    if hi <= lo:
        return np.zeros(values.shape, dtype=np.float32)
    return np.clip((values - lo) / (hi - lo), 0.0, 1.0).astype(np.float32)


def compare_band(
    band: np.ndarray, valid: np.ndarray, mean: float, std: float, name: str
) -> dict[str, Any]:
    """Statistics of one band over valid pixels and their comparison with EuroSAT mean/std."""
    p2, median, p98 = band_percentiles(band, valid)
    z = zscore(median, mean, std)
    return {
        "band": name,
        "p2": p2,
        "median": median,
        "p98": p98,
        "eurosat_mean": mean,
        "eurosat_std": std,
        "z": z,
        "flag": flag_z(z),
        "within_3std": fraction_within(band, valid, mean, std),
    }



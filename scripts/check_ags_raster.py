def find_gdalbuildvrt() -> str | None:
    """Locate ``gdalbuildvrt`` on PATH or next to the Python executable (conda env ``bin/``)."""
    found = shutil.which("gdalbuildvrt")
    if found:
        return found
    candidate = Path(sys.executable).parent / "gdalbuildvrt"
    return str(candidate) if candidate.exists() else None


def build_vrt(tifs: Sequence[Path], vrt_path: Path) -> Path:
    """Build a VRT mosaic of ``tifs`` with ``gdalbuildvrt``.

    Raises:
        RuntimeError: if ``gdalbuildvrt`` is not found or fails.
    """
    exe = find_gdalbuildvrt()
    if exe is None:
        raise RuntimeError(
            "gdalbuildvrt not found on PATH or next to the Python executable. Install GDAL "
            "(conda install -c conda-forge gdal) or add its bin/ directory to PATH."
        )
    vrt_path.parent.mkdir(parents=True, exist_ok=True)
    cmd = [exe, "-overwrite", str(vrt_path), *map(str, sorted(tifs))]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"gdalbuildvrt failed: {proc.stderr.strip()}")
    return vrt_path


def check_raster_properties(src: Any) -> dict[str, Any]:
    """Validate an open rasterio dataset: 14 bands, uint16, EPSG:32613, 10 m pixels.

    Returns:
        dict of raster properties used by the report.

    Raises:
        ValueError: with a message naming the first violated property.
    """
    if src.count != N_BANDS:
        raise ValueError(f"expected {N_BANDS} bands, found {src.count}")
    dtypes = set(src.dtypes)
    if dtypes != {"uint16"}:
        raise ValueError(f"expected dtype uint16, found {sorted(dtypes)}")
    epsg = src.crs.to_epsg() if src.crs else None
    if f"EPSG:{epsg}" != EXPORT_CRS:
        raise ValueError(f"expected CRS {EXPORT_CRS}, found {src.crs}")
    xres, yres = (abs(r) for r in src.res)
    if not (np.isclose(xres, PIXEL_SIZE_M) and np.isclose(yres, PIXEL_SIZE_M)):
        raise ValueError(f"expected {PIXEL_SIZE_M} m pixels, found {src.res}")
    left, top = src.transform.c, src.transform.f
    return {
        "width": src.width,
        "height": src.height,
        "bands": src.count,
        "dtype": "uint16",
        "crs": EXPORT_CRS,
        "pixel_size": PIXEL_SIZE_M,
        "origin_aligned": grid_offset_px(left, top) is not None,
        "grid_offset_px": grid_offset_px(left, top),
    }


def check_vrt_properties(path: Path) -> dict[str, Any]:
    """Open ``path`` with rasterio and run :func:`check_raster_properties`."""
    import rasterio

    with rasterio.open(path) as src:
        return check_raster_properties(src)


def load_eurosat_stats(path: Path) -> dict[str, dict[str, float]]:
    """Load EuroSAT per-band mean/std; raises ``FileNotFoundError`` with a hint if missing."""
    if not path.exists():
        raise FileNotFoundError(
            f"EuroSAT statistics not found: {path}. Run `python scripts/prepare_eurosat.py` first."
        )
    stats = json.loads(path.read_text())
    missing = [b for b in eurosat_band_names() if b not in stats]
    if missing:
        raise ValueError(f"{path} lacks bands {missing}")
    return stats


def rasterize_boundary(boundary: Path, src: Any) -> np.ndarray:
    """Boolean in-state mask on the grid of ``src``, rasterized from a vector file."""
    import geopandas as gpd
    from rasterio.features import rasterize

    gdf = gpd.read_file(boundary).to_crs(src.crs)
    shapes = [(geom, 1) for geom in gdf.geometry if geom is not None and not geom.is_empty]
    mask = rasterize(
        shapes, out_shape=(src.height, src.width), transform=src.transform, dtype="uint8"
    )
    return mask.astype(bool)


def write_preview(src: Any, path: Path, max_side: int = PREVIEW_MAX_SIDE) -> None:
    """Write the RGB preview (B04, B03, B02; 2-98 % stretch per band) as a PNG.

    The image is read downsampled with ``out_shape`` and nearest-neighbour resampling, so edge
    pixels are not darkened by blending with zeros. Pixels without observation are transparent.
    """
    import matplotlib.image as mpimg
    from rasterio.enums import Resampling

    scale = min(1.0, max_side / max(src.width, src.height))
    shape = (max(1, round(src.height * scale)), max(1, round(src.width * scale)))
    names = eurosat_band_names()
    idx = [names.index(b) + 1 for b in RGB_BANDS]
    data = src.read(idx, out_shape=(len(idx), *shape), resampling=Resampling.nearest)
    valid = src.read(N_BANDS, out_shape=shape, resampling=Resampling.nearest) > 0
    rgb = np.stack([stretch(data[i], valid) for i in range(len(idx))], axis=-1)
    rgba = np.concatenate([rgb, valid[..., None].astype(np.float32)], axis=-1)
    path.parent.mkdir(parents=True, exist_ok=True)
    mpimg.imsave(path, rgba)


def _display_path(path: Path) -> str:
    """``path`` relative to the repository root when possible (no user-specific prefix)."""
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def run_check(
    raw_dir: Path,
    stats_path: Path,
    report_path: Path,
    preview_path: Path,
    boundary: Path | None = None,
    vrt_path: Path | None = None,
) -> dict[str, Any]:
    """Run the whole check and write the report and the preview.

    Raises:
        FileNotFoundError: if the EuroSAT statistics or the raw tiles are missing.
        ValueError: if the raster properties are wrong.
        RuntimeError: if the VRT cannot be built.
    """
    import rasterio

    stats = load_eurosat_stats(stats_path)
    tifs = sorted(raw_dir.glob(f"{FILE_PREFIX}*.tif"))
    if not tifs:
        raise FileNotFoundError(
            f"no files matching {raw_dir / (FILE_PREFIX + '*.tif')}; download the Drive export "
            "first."
        )
    vrt_path = vrt_path or raw_dir / f"{FILE_PREFIX}.vrt"
    build_vrt(tifs, vrt_path)

    names = eurosat_band_names()
    with rasterio.open(vrt_path) as src:
        info = check_raster_properties(src)
        info["source"] = _display_path(vrt_path)
        info["n_tiles"] = len(tifs)

        valid_obs = src.read(N_BANDS)
        valid = valid_mask(valid_obs)
        inside = rasterize_boundary(boundary, src) if boundary is not None else None
        obs = summarize_valid_obs(valid_obs, inside)
        obs["n_valid"] = int(valid.sum())
        obs["n_total"] = int(valid.size)
        obs["valid_pixels"] = summarize_valid_pixels(valid_obs)
        del valid_obs

        rows = []
        for i, name in enumerate(names, start=1):
            band = src.read(i)  # one band at a time
            rows.append(compare_band(band, valid, stats[name]["mean"], stats[name]["std"], name))
            del band

        write_preview(src, preview_path)

    warnings = collect_warnings(rows, obs, info)
    try:
        preview_rel = str(preview_path.relative_to(report_path.parent))
    except ValueError:
        preview_rel = str(preview_path)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(render_report(info, rows, obs, warnings, preview_rel))
    return {"info": info, "rows": rows, "obs": obs, "warnings": warnings}


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--boundary",
        type=Path,
        default=None,
        help="state boundary file (e.g. data/ref/<file>.gpkg) to separate outside-state pixels",
    )
    parser.add_argument("--raw-dir", type=Path, default=ROOT / RAW_DIR)
    parser.add_argument("--stats", type=Path, default=ROOT / STATS_PATH)
    parser.add_argument("--report", type=Path, default=ROOT / REPORT_PATH)
    parser.add_argument("--preview", type=Path, default=ROOT / PREVIEW_PATH)
    args = parser.parse_args(argv)
    try:
        result = run_check(
            args.raw_dir, args.stats, args.report, args.preview, boundary=args.boundary
        )
    except (FileNotFoundError, ValueError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print(f"Wrote {args.report} and {args.preview}")
    for w in result["warnings"]:
        print(f"WARNING: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

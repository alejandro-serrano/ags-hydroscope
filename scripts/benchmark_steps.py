"""Time a few training steps of every run config on MPS and estimate the cost of a full run.

    python scripts/benchmark_steps.py [--steps 100] [--configs resnet50_rgb_imagenet,...]

Uses the same loaders, loss, optimizer and ``run_epoch`` as the real training. Nothing is saved
except the table between the BEGIN/END markers of docs/compute.md.
"""

import argparse
import gc
import math
import time
from datetime import date
from pathlib import Path

import pandas as pd
import torch
import torch.nn as nn

from hydroscope.config import load_config
from hydroscope.data.transforms import get_mean_std, resize_to_input
from hydroscope.models.factory import build_model, count_params
from hydroscope.training.evaluate import get_git_commit, get_git_dirty
from hydroscope.training.loop_utils import accumulation_steps, make_eurosat_loader
from hydroscope.training.train import run_epoch, set_seed
from hydroscope.utils.device import PeakMemoryTracker

ROOT = Path(__file__).resolve().parents[1]
CONFIGS_DIR = ROOT / "configs"
COMPUTE_DOC = ROOT / "docs" / "compute.md"
BEGIN = "<!-- BEGIN generated by scripts/benchmark_steps.py -->"
END = "<!-- END generated by scripts/benchmark_steps.py -->"

RUN_IDS = [
    "resnet50_rgb_imagenet",
    "resnet50_ms13_imagenet",
    "efficientnet_b0_rgb_imagenet",
    "efficientnet_b0_ms13_imagenet",
    "vit_small_rgb_imagenet",
    "vit_small_ms13_imagenet",
    "resnet50_ms13_ssl4eo",
    "vit_small_ms13_ssl4eo",
]
N_TRAIN = 16200
N_VAL = 5400
N_TEST = 5400  # eurosat_test has as many patches as val (docs/data_eurosat.md)
WARMUP_STEPS = 5
VAL_BATCHES = 20


def check_mps() -> None:
    """Stop with a clear message if this machine has no MPS device."""
    if not torch.backends.mps.is_available():
        raise RuntimeError(
            "This benchmark must run on Apple silicon (MPS), but MPS is not available"
        )


def benchmark_train(model, loader, cfg: dict, device, tracker, steps: int) -> float:
    """Seconds per optimizer step, measured with ``run_epoch`` itself.

    A first call of WARMUP_STEPS steps is not timed. The second call continues the same
    ``state`` (same learning-rate schedule) until step ``steps`` and is timed.
    """
    accum = accumulation_steps(cfg["optim"]["batch_size"], cfg["optim"]["micro_batch_size"])
    steps_per_epoch = math.ceil(len(loader) / accum)
    state = {
        "step": 0,
        "total_steps": cfg["schedule"]["max_epochs"] * steps_per_epoch,
        "warmup_steps": cfg["schedule"]["warmup_epochs"] * steps_per_epoch,
        "base_lr": cfg["optim"]["lr"],
        "max_steps": WARMUP_STEPS,
        "stop": False,
        "tracker": tracker,
    }
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=cfg["optim"]["lr"], weight_decay=cfg["optim"]["weight_decay"]
    )
    criterion = nn.CrossEntropyLoss()
    size = cfg["data"]["input_size"]
    run_epoch(model, loader, criterion, device, size, optimizer, accum, state)
    torch.mps.synchronize()
    state["max_steps"] = steps
    first_timed_step = state["step"]
    start = time.time()
    run_epoch(model, loader, criterion, device, size, optimizer, accum, state)
    torch.mps.synchronize()
    elapsed = time.time() - start
    return elapsed / (state["step"] - first_timed_step)


def benchmark_val(model, loader, device, size: int, tracker) -> float:
    """Seconds per validation batch: one untimed warm batch, then VAL_BATCHES timed ones."""
    model.eval()
    start = 0.0
    n_timed = 0
    with torch.no_grad():
        for i, (x, _labels) in enumerate(loader):
            x = x.to(device)  # (N, C, 64, 64)
            x = resize_to_input(x, size)  # (N, C, 224, 224)
            model(x).argmax(dim=1).cpu()  # (N,) the copy waits for the GPU
            tracker.update()
            if i == 0:
                torch.mps.synchronize()
                start = time.time()
            else:
                n_timed += 1
            if n_timed == VAL_BATCHES:
                break
    torch.mps.synchronize()
    return (time.time() - start) / n_timed


def estimate(s_step: float, s_val: float, batch: int, val_batch: int, epochs: int) -> dict:
    """Minutes per epoch and hours per run (upper bound: early stopping may end sooner).

    A run is ``epochs`` x (train steps + val batches), plus the final val predict and the
    eurosat_test predict, both at the val rate.
    """
    train_steps = math.ceil(N_TRAIN / batch)
    val_batches = math.ceil(N_VAL / val_batch)
    test_batches = math.ceil(N_TEST / val_batch)
    epoch_s = train_steps * s_step + val_batches * s_val
    run_s = epochs * epoch_s + (val_batches + test_batches) * s_val
    return {"min_epoch": epoch_s / 60, "h_run": run_s / 3600}


def benchmark_one(run_id: str, steps: int) -> dict:
    """Benchmark one config and return its table row."""
    cfg = load_config(CONFIGS_DIR / f"{run_id}.yaml")
    cfg["device"] = "mps"
    set_seed(cfg["seed"])
    device = torch.device("mps")
    mean, std = get_mean_std(cfg["init"], cfg["bands"], cfg["data"]["stats"])
    train_loader = make_eurosat_loader(cfg, "train", mean, std, train=True)
    val_loader = make_eurosat_loader(cfg, "val", mean, std, train=False)
    if len(train_loader.dataset) != N_TRAIN or len(val_loader.dataset) != N_VAL:
        raise ValueError(
            f"expected {N_TRAIN} train / {N_VAL} val samples, got "
            f"{len(train_loader.dataset)} / {len(val_loader.dataset)}"
        )
    model = build_model(cfg["model"], cfg["bands"], cfg["init"]).to(device)
    tracker = PeakMemoryTracker(device)
    s_step = benchmark_train(model, train_loader, cfg, device, tracker, steps)
    s_val = benchmark_val(model, val_loader, device, cfg["data"]["input_size"], tracker)
    est = estimate(
        s_step,
        s_val,
        cfg["optim"]["batch_size"],
        cfg["optim"]["micro_batch_size"],
        cfg["schedule"]["max_epochs"],
    )
    row = {
        "run_id": run_id,
        "init": cfg["init"],
        "params_m": count_params(model) / 1e6,
        "s_step": s_step,
        "s_val_batch": s_val,
        "peak_mb": tracker.peak_mb,
        "min_epoch": est["min_epoch"],
        "h_run": est["h_run"],
    }
    del model, train_loader, val_loader  # free memory before the next config
    gc.collect()
    torch.mps.empty_cache()
    return row


def rows_to_markdown(rows: list[dict]) -> str:
    """Markdown table: one line per config."""
    lines = [
        "| run_id | params (M) | s/step | s/val batch | peak MB | min/epoch | h/run (15 epochs) |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in rows:
        lines.append(
            f"| {r['run_id']} | {r['params_m']:.1f} | {r['s_step']:.3f} | {r['s_val_batch']:.3f} "
            f"| {r['peak_mb']:.0f} | {r['min_epoch']:.1f} | {r['h_run']:.2f} |"
        )
    return "\n".join(lines)


def total_hours(rows: list[dict], init: str) -> float:
    """Sum of h/run over the rows with this init (imagenet = E1, ssl4eo = E2)."""
    total = 0.0
    for r in rows:
        if r["init"] == init:
            total += r["h_run"]
    return total


def build_generated_block(rows: list[dict], steps: int) -> str:
    """Markdown between the BEGIN/END markers of docs/compute.md."""
    lines = [
        BEGIN,
        "",
        f"Date: {date.today().isoformat()} | device: mps | git commit: {get_git_commit()} "
        f"(dirty: {get_git_dirty()}) | timed steps: up to step {steps} after {WARMUP_STEPS} "
        f"warm-up steps | val batches: {VAL_BATCHES}",
        "",
        rows_to_markdown(rows),
        "",
        f"Total E1 (imagenet runs): {total_hours(rows, 'imagenet'):.1f} h",
        "",
        f"Total E2 (ssl4eo runs): {total_hours(rows, 'ssl4eo'):.1f} h",
        "",
        END,
    ]
    return "\n".join(lines)


def replace_generated_block(text: str, block: str) -> str:
    """Replace the BEGIN/END section of ``text`` with ``block``."""
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("BEGIN/END markers not found in docs/compute.md")
    return text[:start] + block + text[end + len(END) :]


def main() -> None:
    parser = argparse.ArgumentParser(description="Benchmark training steps on MPS")
    parser.add_argument("--steps", type=int, default=100, help="optimizer steps to reach")
    parser.add_argument("--configs", default=",".join(RUN_IDS), help="comma-separated run_ids")
    args = parser.parse_args()
    check_mps()
    text = COMPUTE_DOC.read_text()
    replace_generated_block(text, "")  # fail early if the markers are missing
    rows = []
    for run_id in args.configs.split(","):
        row = benchmark_one(run_id, args.steps)
        rows.append(row)
        print(
            f"{row['run_id']} | {row['params_m']:.1f}M params | {row['s_step']:.3f} s/step | "
            f"{row['s_val_batch']:.3f} s/val batch | peak {row['peak_mb']:.0f} MB | "
            f"{row['min_epoch']:.1f} min/epoch | {row['h_run']:.2f} h/run"
        )
    print(pd.DataFrame(rows).drop(columns=["init"]).round(3).to_string(index=False))
    print(f"E1 (imagenet): {total_hours(rows, 'imagenet'):.1f} h")
    print(f"E2 (ssl4eo): {total_hours(rows, 'ssl4eo'):.1f} h")
    block = build_generated_block(rows, args.steps)
    COMPUTE_DOC.write_text(replace_generated_block(text, block))


if __name__ == "__main__":
    main()

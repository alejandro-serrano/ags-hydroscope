"""Write docs/explorer/samples.png, gradcam.png and images.js, the images of two Explorer tabs.

Run: python scripts/make_explorer_images.py
- samples.png: 6 random patches per class (seed 0) of the EuroSAT test set and of the labeled
  Aguascalientes patches (finetune + test), as RGB tiles. One 2-98 % stretch per dataset,
  computed on the patches shown, as in make_gradcam.py.
- gradcam.png: the patches and models of the paper's Grad-CAM figures, read from
  paper/figures/gradcam_samples.csv (they are not chosen again). For every patch, its RGB tile
  and one Grad-CAM map per model, saved alone with the jet colormap. The page blends each map
  over the RGB tile; with opacity 0.5 it looks like overlay_cam in the paper.
- images.js: where each 64 x 64 tile sits in the sprites (16 tiles per row) and what it shows.

Missing inputs (EuroSAT cache, data/ags/labels.csv, patches, checkpoints) are not an error: the
matching part of images.js is null and the script says why. It is not called by
make_results.py. The output is deterministic: the same inputs give the same files, byte by byte.
"""

import json
import random
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd
import torch
from make_gradcam import CKPT_DIR, FIGURES_DIR, ROOT, load_model, raw_patch_ags
from PIL import Image

from hydroscope.data.ags import AGS_SPLITS, AguascalientesDataset
from hydroscope.data.eurosat import CLASSES, EuroSATDataset, cache_paths
from hydroscope.data.labels import SKIP, load_labels
from hydroscope.explain.gradcam import compute_gradcam, prepare_patch, rgb_limits, to_rgb_image

EUROSAT_CACHE = ROOT / "data" / "eurosat" / "cache"
LABELS_CSV = ROOT / "data" / "ags" / "labels.csv"
PATCHES_DIR = ROOT / "data" / "ags" / "patches"
GRADCAM_CSV = FIGURES_DIR / "gradcam_samples.csv"
OUT_DIR = ROOT / "docs" / "explorer"
SAMPLES_PNG = "samples.png"
GRADCAM_PNG = "gradcam.png"
JS_NAME = "images.js"
HEADER = "// Generated by scripts/make_explorer_images.py. Do not edit by hand."
PREFIX = "window.HYDROSCOPE_IMAGES = "
SCHEMA_VERSION = 1

TILE = 64  # pixels per side of one tile (one patch)
TILES_PER_ROW = 16
PER_CLASS = 6
SEED = 0
LAST_BLOCK_SUFFIX = "_ft-last_block"


# ---------- sprite ----------


def tile_position(k: int) -> tuple[int, int]:
    """Top-left pixel (x, y) of tile number ``k`` in a sprite of 16 tiles per row."""
    return (k % TILES_PER_ROW) * TILE, (k // TILES_PER_ROW) * TILE


def add_tile(tiles: list[np.ndarray], image: np.ndarray) -> dict:
    """Append an RGB image (64, 64, 3) in [0, 1] as 8-bit pixels; return its {"x", "y"}."""
    x, y = tile_position(len(tiles))
    tiles.append(np.round(image * 255).astype(np.uint8))
    return {"x": x, "y": y}


def build_sprite(tiles: list[np.ndarray]) -> Image.Image:
    """White RGB image with tile ``k`` pasted at tile_position(k)."""
    n_rows = (len(tiles) + TILES_PER_ROW - 1) // TILES_PER_ROW
    sprite = Image.new("RGB", (TILES_PER_ROW * TILE, n_rows * TILE), "white")
    for k, tile in enumerate(tiles):
        sprite.paste(Image.fromarray(tile), tile_position(k))
    return sprite


def images_js_text(meta: dict) -> str:
    """The two lines of images.js: the header comment and the metadata assigned to a global."""
    return f"{HEADER}\n{PREFIX}{json.dumps(meta)};\n"


# ---------- inputs ----------


def load_eurosat(cache_dir: Path) -> tuple[EuroSATDataset, list[int]] | None:
    """EuroSAT test set (ms13, raw values) and its labels, or None if the cache is missing."""
    x_path, y_path = cache_paths(cache_dir, "test")
    if not x_path.exists() or not y_path.exists():
        print(f"note: no EuroSAT test cache in {cache_dir} (run scripts/prepare_eurosat.py)")
        return None
    dataset = EuroSATDataset("test", bands="ms13", cache_dir=cache_dir)
    labels = [int(dataset[i]["label"]) for i in range(len(dataset))]
    return dataset, labels


def ags_missing_reason(labels_csv: Path, patches_dir: Path) -> str:
    """Why the labeled Aguascalientes patches cannot be read ("" if they can)."""
    if not labels_csv.exists():
        return f"{labels_csv} not found (it comes with the release)"
    table = load_labels(labels_csv)
    table = table[table["label"] != SKIP]
    for split in AGS_SPLITS:
        if not (table["split"] == split).any():
            return f"no labeled patches in split {split!r} of {labels_csv}"
    missing = 0
    for cell_id in table["cell_id"]:
        if not (patches_dir / f"{cell_id}.tif").exists():
            missing += 1
    if missing > 0:
        return f"{missing} labeled patches missing in {patches_dir}"
    return ""


def load_ags(labels_csv: Path, patches_dir: Path) -> dict[str, AguascalientesDataset] | None:
    """The finetune and test datasets (raw values, no augmentation), or None if inputs miss."""
    reason = ags_missing_reason(labels_csv, patches_dir)
    if reason:
        print(f"note: {reason}")
        return None
    datasets = {}
    for split in AGS_SPLITS:
        datasets[split] = AguascalientesDataset(
            split,
            "ms13",
            torch.zeros(13),
            torch.ones(13),
            train=False,
            labels_csv=labels_csv,
            patches_dir=patches_dir,
        )
    return datasets


# ---------- samples tab ----------


def pick_per_class(labels: list[int], per_class: int, seed: int) -> dict[str, list[int]]:
    """Seeded random choice of up to ``per_class`` positions of each class, in CLASSES order."""
    rng = random.Random(seed)
    chosen = {}
    for class_id, class_name in enumerate(CLASSES):
        indices = [i for i, label in enumerate(labels) if label == class_id]
        chosen[class_name] = rng.sample(indices, min(per_class, len(indices)))
    return chosen


def eurosat_samples(dataset: EuroSATDataset, labels: list[int], tiles: list) -> dict:
    """Tiles and per-class counts of the EuroSAT test set."""
    chosen = pick_per_class(labels, PER_CLASS, SEED)
    raws = {}
    for class_name in CLASSES:
        for i in chosen[class_name]:
            raws[i] = dataset[i]["image"].numpy()  # (13, 64, 64) raw values
    limits = rgb_limits(np.stack(list(raws.values())))

    count = {}
    class_tiles = {}
    for class_id, class_name in enumerate(CLASSES):
        count[class_name] = labels.count(class_id)
        class_tiles[class_name] = []
        for i in chosen[class_name]:
            tile = add_tile(tiles, to_rgb_image(raws[i], limits))
            tile["index"] = i
            class_tiles[class_name].append(tile)
    return {"split": "test", "count": count, "tiles": class_tiles}


def ags_samples(datasets: dict[str, AguascalientesDataset], tiles: list) -> dict:
    """Tiles and per-class, per-split counts of the labeled Aguascalientes patches."""
    pool = []  # (split, position in that split), finetune first, then test
    labels = []
    for split in AGS_SPLITS:
        for i, label in enumerate(datasets[split].labels):
            pool.append((split, i))
            labels.append(label)
    chosen = pick_per_class(labels, PER_CLASS, SEED)
    shown = []
    for class_name in CLASSES:
        for k in chosen[class_name]:
            split, i = pool[k]
            shown.append(raw_patch_ags(datasets[split], i))
    limits = rgb_limits(np.stack(shown))

    count = {}
    class_tiles = {}
    for class_id, class_name in enumerate(CLASSES):
        count[class_name] = {}
        for split in AGS_SPLITS:
            count[class_name][split] = datasets[split].labels.count(class_id)
        class_tiles[class_name] = []
        for k in chosen[class_name]:
            split, i = pool[k]
            tile = add_tile(tiles, to_rgb_image(raw_patch_ags(datasets[split], i), limits))
            tile["cell_id"] = datasets[split].cell_ids[i]
            tile["split"] = split
            class_tiles[class_name].append(tile)
    return {"count": count, "tiles": class_tiles}


def build_samples(eurosat: tuple | None, ags: dict | None, tiles: list) -> dict | None:
    """The "samples" part of images.js (None if neither dataset is available)."""
    if eurosat is None and ags is None:
        print("note: no EuroSAT and no Aguascalientes patches; samples is null")
        return None
    samples = {"file": SAMPLES_PNG, "per_class": PER_CLASS, "seed": SEED, "classes": list(CLASSES)}
    samples["eurosat"] = None
    if eurosat is not None:
        samples["eurosat"] = eurosat_samples(eurosat[0], eurosat[1], tiles)
    samples["ags"] = None
    if ags is not None:
        samples["ags"] = ags_samples(ags, tiles)
    return samples


# ---------- Grad-CAM tab ----------


def unique_in_order(values: list) -> list:
    """The values without repeats, in the order they first appear."""
    result = []
    for value in values:
        if value not in result:
            result.append(value)
    return result


def raw_patch(dataset: str, row: pd.Series, eurosat: tuple | None, ags: dict | None) -> np.ndarray:
    """Raw patch (13, 64, 64) of a gradcam_samples.csv row, checked against its true class."""
    index = int(row["index"])
    if dataset == "eurosat_test":
        sample = eurosat[0][index]
        label = CLASSES[int(sample["label"])]
        raw = sample["image"].numpy()
    else:
        ags_test = ags["test"]
        if ags_test.cell_ids[index] != row["cell_id"]:
            raise ValueError(
                f"Aguascalientes test patch {index} is {ags_test.cell_ids[index]}, but "
                f"gradcam_samples.csv says {row['cell_id']}: labels.csv changed since "
                "scripts/make_gradcam.py was run"
            )
        label = CLASSES[ags_test.labels[index]]
        raw = raw_patch_ags(ags_test, index)
    if label != row["true_label"]:
        raise ValueError(
            f"{dataset} patch {index} is {label}, but gradcam_samples.csv says {row['true_label']}"
        )
    return raw


def first_rows(table: pd.DataFrame) -> list[pd.Series]:
    """The first CSV row of each patch (one patch has one row per model), in CSV order."""
    rows = []
    for index in unique_in_order(list(table["index"])):
        rows.append(table[table["index"] == index].iloc[0])
    return rows


def dataset_limits(
    table: pd.DataFrame, available: dict[str, bool], eurosat: tuple | None, ags: dict | None
) -> dict[str, np.ndarray]:
    """One RGB stretch per dataset, over all its patches in the CSV, as in make_gradcam.py."""
    limits = {}
    for dataset in unique_in_order(list(table["dataset"])):
        if not available[dataset]:
            continue
        raws = []
        for row in first_rows(table[table["dataset"] == dataset]):
            raws.append(raw_patch(dataset, row, eurosat, ags))
        limits[dataset] = rgb_limits(np.stack(raws))
    return limits


def gradcam_columns(table: pd.DataFrame) -> list[dict]:
    """One column per model of a figure, in CSV order."""
    columns = []
    for run_id in unique_in_order(list(table["run_id"])):
        stage = table[table["run_id"] == run_id]["stage"].iloc[0]
        base_run_id = run_id.removesuffix(LAST_BLOCK_SUFFIX)
        columns.append({"run_id": run_id, "base_run_id": base_run_id, "stage": stage})
    return columns


def compute_maps(run_id: str, raws: list[np.ndarray]) -> list[tuple[np.ndarray, str]]:
    """Grad-CAM map (64, 64) in [0, 1] and predicted class of every patch, for one model."""
    model, meta, name, mean, std = load_model(run_id)  # on CPU, as in make_gradcam.py
    maps = []
    for raw in raws:
        image = prepare_patch(torch.from_numpy(raw), meta["bands"], mean, std)  # (C, 64, 64)
        cam, pred = compute_gradcam(model, name, image)
        maps.append((cam, CLASSES[pred]))
    return maps


def map_entry(
    figure: str, expected: pd.Series, cam: np.ndarray, predicted: str, tiles: list
) -> dict:
    """One map of a row: the jet-colored map alone (not blended), after checking the CSV."""
    if predicted != expected["predicted_label"]:
        raise ValueError(
            f"{figure}, patch {expected['index']}, {expected['run_id']}: the model predicts "
            f"{predicted}, but gradcam_samples.csv says {expected['predicted_label']}"
        )
    colors = matplotlib.colormaps["jet"](cam)[:, :, :3]  # (64, 64) -> (64, 64, 3)
    entry = {
        "run_id": expected["run_id"],
        "stage": expected["stage"],
        "predicted_label": predicted,
        "correct": bool(expected["correct"]),
    }
    entry.update(add_tile(tiles, colors))
    return entry


def gradcam_figure(
    figure: str,
    table: pd.DataFrame,
    limits: dict,
    eurosat: tuple | None,
    ags: dict | None,
    tiles: list,
) -> dict:
    """One figure of gradcam_samples.csv: its columns (models) and rows (patches)."""
    dataset = table["dataset"].iloc[0]
    columns = gradcam_columns(table)
    patches = first_rows(table)
    raws = []
    for row in patches:
        raws.append(raw_patch(dataset, row, eurosat, ags))
    maps = []  # maps[column][row] = (cam, predicted class); each model is loaded once
    for column in columns:
        maps.append(compute_maps(column["run_id"], raws))

    rows = []
    for r, row in enumerate(patches):
        item = {
            "index": int(row["index"]),
            "cell_id": row["cell_id"],
            "true_label": row["true_label"],
            "selection_rule": row["selection_rule"],
            "rgb": add_tile(tiles, to_rgb_image(raws[r], limits[dataset])),
            "maps": [],
        }
        for c, column in enumerate(columns):
            same = (table["index"] == row["index"]) & (table["run_id"] == column["run_id"])
            cam, predicted = maps[c][r]
            item["maps"].append(map_entry(figure, table[same].iloc[0], cam, predicted, tiles))
        rows.append(item)
    print(f"{figure}: {len(rows)} patches x {len(columns)} models, predictions match the CSV")
    return {"name": figure, "dataset": dataset, "columns": columns, "rows": rows}


def figure_missing_reason(table: pd.DataFrame, available: dict[str, bool]) -> str:
    """Why a figure cannot be drawn ("" if it can): its dataset or a checkpoint is missing."""
    dataset = table["dataset"].iloc[0]
    if not available[dataset]:
        return f"no {dataset} patches"
    missing = []
    for run_id in unique_in_order(list(table["run_id"])):
        if not (CKPT_DIR / f"{run_id}.pt").exists():
            missing.append(run_id)
    if missing:
        return f"checkpoints missing in {CKPT_DIR}: {', '.join(missing)}"
    return ""


def build_gradcam(
    csv_path: Path, eurosat: tuple | None, ags: dict | None, tiles: list
) -> dict | None:
    """The "gradcam" part of images.js (None if no figure can be drawn)."""
    if not csv_path.exists():
        print(f"note: {csv_path} not found (run scripts/make_gradcam.py); gradcam is null")
        return None
    table = pd.read_csv(csv_path, keep_default_na=False)  # EuroSAT rows have cell_id ""
    available = {"eurosat_test": eurosat is not None, "ags_test": ags is not None}
    limits = dataset_limits(table, available, eurosat, ags)
    figures = []
    for figure in unique_in_order(list(table["figure"])):
        figure_table = table[table["figure"] == figure]
        reason = figure_missing_reason(figure_table, available)
        if reason:
            print(f"note: {figure} left out: {reason}")
            continue
        figures.append(gradcam_figure(figure, figure_table, limits, eurosat, ags, tiles))
    if not figures:
        print("note: no Grad-CAM figure can be drawn; gradcam is null")
        return None
    return {"file": GRADCAM_PNG, "figures": figures}


# ---------- output ----------


def write_images(
    eurosat_cache: Path = EUROSAT_CACHE,
    labels_csv: Path = LABELS_CSV,
    patches_dir: Path = PATCHES_DIR,
    gradcam_csv: Path = GRADCAM_CSV,
    out_dir: Path = OUT_DIR,
) -> list[Path]:
    """Write the sprites that have content and images.js. Returns the paths written."""
    eurosat = load_eurosat(eurosat_cache)
    ags = load_ags(labels_csv, patches_dir)
    sample_tiles = []
    gradcam_tiles = []
    meta = {"schema_version": SCHEMA_VERSION, "tile": TILE}
    meta["samples"] = build_samples(eurosat, ags, sample_tiles)
    meta["gradcam"] = build_gradcam(gradcam_csv, eurosat, ags, gradcam_tiles)

    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    if meta["samples"] is not None:
        build_sprite(sample_tiles).save(out_dir / SAMPLES_PNG, optimize=True)
        written.append(out_dir / SAMPLES_PNG)
    if meta["gradcam"] is not None:
        build_sprite(gradcam_tiles).save(out_dir / GRADCAM_PNG, optimize=True)
        written.append(out_dir / GRADCAM_PNG)
    (out_dir / JS_NAME).write_text(images_js_text(meta))
    written.append(out_dir / JS_NAME)
    return written


def main() -> None:
    written = write_images()
    for path in written:
        print(f"Written: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

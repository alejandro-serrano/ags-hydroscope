"""Write docs/explorer/basemap.jpg and basemap.js, the background image of the spatial split demo.

Run: python scripts/make_explorer_basemap.py
The image is a mosaic of the cell previews of data/ags/previews (the same RGB previews used for
labeling, with the global stretch of the composite): each preview is reduced to 8 x 8 pixels and
pasted at its (row, col) on a white background. The previews are not in git, so without them the
script prints a note and leaves the existing files as they are. It is not called by
make_results.py: the image does not change with the results.
The output is deterministic: the same previews give the same files, byte by byte.
"""

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PREVIEWS_DIR = ROOT / "data" / "ags" / "previews"
OUT_DIR = ROOT / "docs" / "explorer"
IMAGE_NAME = "basemap.jpg"
JS_NAME = "basemap.js"
HEADER = (
    "// Generated by scripts/make_explorer_basemap.py from data/ags/previews/*.png. "
    "Do not edit by hand."
)
PREFIX = "window.HYDROSCOPE_BASEMAP = "
SCHEMA_VERSION = 1
PIXELS_PER_CELL = 8
JPEG_QUALITY = 85


def parse_cell_id(cell_id: str) -> tuple[int, int]:
    """'r0083_c0148' -> (83, 148)."""
    row_part, col_part = cell_id.split("_")
    return int(row_part[1:]), int(col_part[1:])


def preview_paths(previews_dir: Path) -> list[Path]:
    """Cell previews (rNNNN_cNNNN.png) sorted by name; stretch_rgb.json is left out."""
    return sorted(previews_dir.glob("r*_c*.png"))


def basemap_extent(cells: list[tuple[int, int]]) -> dict:
    """First row and column of the mosaic and its size in cells."""
    rows = [row for row, col in cells]
    cols = [col for row, col in cells]
    return {
        "row0": min(rows),
        "col0": min(cols),
        "n_rows": max(rows) - min(rows) + 1,
        "n_cols": max(cols) - min(cols) + 1,
    }


def build_mosaic(paths: list[Path], extent: dict) -> Image.Image:
    """White RGB image with every preview reduced to 8 x 8 px at its (row, col)."""
    size = PIXELS_PER_CELL
    width = extent["n_cols"] * size
    height = extent["n_rows"] * size
    mosaic = Image.new("RGB", (width, height), "white")
    for path in paths:
        row, col = parse_cell_id(path.stem)
        with Image.open(path) as preview:
            small = preview.convert("RGBA").resize((size, size), Image.BOX)  # (256, 256) -> (8, 8)
        x = (col - extent["col0"]) * size
        y = (row - extent["row0"]) * size
        mosaic.paste(small, (x, y), small)  # the alpha channel is the paste mask
    return mosaic


def basemap_js_text(meta: dict) -> str:
    """The two lines of basemap.js: the header comment and the metadata assigned to a global."""
    return f"{HEADER}\n{PREFIX}{json.dumps(meta)};\n"


def write_basemap(previews_dir: Path = PREVIEWS_DIR, out_dir: Path = OUT_DIR) -> list[Path]:
    """Write basemap.jpg and basemap.js. Returns the paths written (empty without previews)."""
    paths = preview_paths(previews_dir)
    if not paths:
        # The previews are not in git (they come from hydroscope.geo.tiling). Without them we
        # keep the files written by the last run that had them.
        print(f"note: no previews in {previews_dir}; basemap files left unchanged")
        return []
    cells = [parse_cell_id(path.stem) for path in paths]
    extent = basemap_extent(cells)
    mosaic = build_mosaic(paths, extent)

    meta = {"schema_version": SCHEMA_VERSION, "file": IMAGE_NAME}
    meta.update(extent)
    meta["pixels_per_cell"] = PIXELS_PER_CELL

    out_dir.mkdir(parents=True, exist_ok=True)
    image_path = out_dir / IMAGE_NAME
    mosaic.save(image_path, "JPEG", quality=JPEG_QUALITY)
    js_path = out_dir / JS_NAME
    js_path.write_text(basemap_js_text(meta))
    return [image_path, js_path]


def main() -> None:
    written = write_basemap()
    for path in written:
        print(f"Written: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

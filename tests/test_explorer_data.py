"""scripts/make_explorer_data.py: data.js for the explorer page (no data/ags/labels.csv needed)."""

import json
import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
# make_explorer_data imports make_results, so the scripts folder must be importable.
sys.path.insert(0, str(ROOT / "scripts"))
import make_explorer_data as med  # noqa: E402


def test_macro_f1_drop_and_recovery_match_summary_csv(tmp_path):
    data = med.build_explorer_data(tmp_path / "labels.csv")
    summary = pd.read_csv(ROOT / "paper" / "tables" / "summary.csv").set_index("run_id")
    assert [run["run_id"] for run in data["runs"]] == list(summary.index)
    for run in data["runs"]:
        row = summary.loc[run["run_id"]]
        evaluations = run["evaluations"]
        pairs = [
            (evaluations["zero_shot"]["macro_f1"], row["ags_zero_shot"]),
            (evaluations["head"]["macro_f1"], row["ags_head"]),
            (evaluations["last_block"]["macro_f1"], row["ags_last_block"]),
            (run["summary"]["drop"], row["drop"]),
            (run["summary"]["recovery_head"], row["recovery_head"]),
            (run["summary"]["recovery_last_block"], row["recovery_last_block"]),
        ]
        for value, expected in pairs:
            if math.isnan(expected):
                assert value is None  # NaN is written as null
            else:
                assert abs(value - expected) <= 1e-9


def test_split_is_none_without_labels_csv(tmp_path):
    assert med.split_section(tmp_path / "labels.csv", 541) is None


def test_neighbour_count_on_tiny_grid():
    # f = fine-tune, t = test, . = no labeled cell
    #   row 0:  f . t
    #   row 1:  . t .
    #   row 2:  t . .
    cells = [[0, 0, "finetune"], [0, 2, "test"], [1, 1, "test"], [2, 0, "test"]]
    assert med.count_test_touching_finetune(cells, 4) == 0
    assert med.count_test_touching_finetune(cells, 8) == 1  # only (1, 1), on the diagonal


def test_data_js_starts_with_comment_and_holds_valid_json(tmp_path):
    path = med.write_explorer_data(tmp_path / "data.js", tmp_path / "labels.csv")
    lines = path.read_text().splitlines()
    assert lines[0] == med.HEADER
    assert lines[0].startswith("// Generated by scripts/make_explorer_data.py")
    data = json.loads(lines[1].removeprefix(med.PREFIX).removesuffix(";"))
    assert data["schema_version"] == 1
    assert data["split"] is None
